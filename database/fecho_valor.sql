CREATE TABLE IF NOT EXISTS fecho_valor (
    cod BIGINT NOT NULL AUTO_INCREMENT,
    data DATE NOT NULL,
    moeda_10 INT UNSIGNED NOT NULL DEFAULT 0,
    moeda_20 INT UNSIGNED NOT NULL DEFAULT 0,
    moeda_50 INT UNSIGNED NOT NULL DEFAULT 0,
    moeda_100 INT UNSIGNED NOT NULL DEFAULT 0,
    moeda_200 INT UNSIGNED NOT NULL DEFAULT 0,
    dinheiro_200 INT UNSIGNED NOT NULL DEFAULT 0,
    dinheiro_500 INT UNSIGNED NOT NULL DEFAULT 0,
    dinheiro_1000 INT UNSIGNED NOT NULL DEFAULT 0,
    dinheiro_2000 INT UNSIGNED NOT NULL DEFAULT 0,
    dinheiro_5000 INT UNSIGNED NOT NULL DEFAULT 0,
    tpa DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    notas DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    campos_guardados VARCHAR(255) NOT NULL DEFAULT '',
    cod_utilizador BIGINT NOT NULL,
    data_criacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (cod),
    UNIQUE KEY uq_fecho_valor_data (data),
    KEY ix_fecho_valor_utilizador (cod_utilizador)
) ENGINE=InnoDB DEFAULT CHARSET=utf8;
